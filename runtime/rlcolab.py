def _md_inline(s):
    """Tiny Markdown for hints/prompts shown inside HTML panels."""
    slots = []

    def keep(h):
        slots.append(h)
        return f"\x00{len(slots) - 1}\x00"
    s = re.sub(r"`([^`]+)`", lambda m: keep(f"<code>{html.escape(m.group(1))}</code>"), str(s))
    s = re.sub(r"\$([^$\n]+?)\$", lambda m: keep(f'<span class="math">{html.escape(m.group(1))}</span>'), s)
    s = html.escape(s, quote=False)
    s = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"(^|[^*\w])\*([^*\n]+)\*(?!\w)", r"\1<em>\2</em>", s)
    s = s.replace("\n", "<br>")
    return re.sub(r"\x00(\d+)\x00", lambda m: slots[int(m.group(1))], s)


