def setup(root_dir=None, lesson=None, quiet=False):
    """Connect this notebook: workspace as the working directory, progress file, kernel callbacks."""
    if root_dir:
        _S["root"] = os.path.abspath(root_dir)
    os.makedirs(workspace(), exist_ok=True)
    os.chdir(workspace())                       # exercises save files here (e.g. trained weights)
    _S["lesson"] = lesson
    _ensure_hooks()
    _register_callbacks()
    _install_todo_handler()
    if not os.path.isfile(_pfile()):
        _save(load_progress())
    if not quiet:
        lesson_header(lesson) if lesson else _display(_HTML(_page(_top_bar() + _link_line(), "rs-hdr")))


def _install_todo_handler():
    """Starter code raises NotImplementedError until you fill it in: show that as a short
    'not implemented yet' card instead of a wall of traceback (the cell still counts as failed)."""
    ip = _ip()
    if ip is None or _S.get("todo"):
        return
    _S["todo"] = True

    def handler(shell, etype, value, tb, tb_offset=None):
        frames = [f for f in traceback.extract_tb(tb) if os.path.abspath(f.filename) != os.path.abspath(__file__)]
        f = frames[-1] if frames else None
        what = f"<code>{html.escape(f.name)}()</code>" if f and not f.name.startswith("<") else "This cell"
        line = f" (line {f.lineno})" if f else ""
        try:
            _display(_HTML(_page(
                f'<div class="rs-locked" style="text-align:left;padding:12px 14px"><span class="label">✏️ NOT IMPLEMENTED YET</span>'
                f'<p>{what} still raises <code>NotImplementedError</code>{line}. Fill in its TODOs, run this cell again, '
                f'then run <b>✅ Check</b>.</p></div>')))
        except Exception:
            pass
        name = f.name if f and not f.name.startswith("<") else "this cell"
        stb = [f"NotImplementedError: {name} is not implemented yet{line}. {value}".rstrip(". ") + "."]
        if not shows_stb:   # newer IPython no longer displays what a custom handler returns
            shell._showtraceback(etype, value, stb)
        return stb
    try:
        import inspect
        shows_stb = "_showtraceback" in inspect.getsource(type(ip).set_custom_exc)
    except Exception:
        shows_stb = True
    ip.set_custom_exc((NotImplementedError,), handler)


def _bar_pct(v):
    return f"{max(0.0, min(100.0, v)):.1f}%"


def _ring(pct, label=None, big=False, sub=""):
    r = 16 if not big else 50
    size = 40 if not big else 112
    c = 2 * math.pi * r
    off = c * (1 - pct / 100)
    cx = size / 2
    inner = label if label is not None else f"{pct:.0f}%"
    if big:
        inner = f"{inner}<small>{sub}</small>"
    return (f'<div class="rs-ring{" big" if big else ""}"><svg viewBox="0 0 {size} {size}">'
            f'<circle class="bg" cx="{cx}" cy="{cx}" r="{r}"/>'
            f'<circle class="fg" cx="{cx}" cy="{cx}" r="{r}" stroke-dasharray="{c:.1f}" stroke-dashoffset="{off:.1f}"/>'
            f'</svg><span>{inner}</span></div>')


