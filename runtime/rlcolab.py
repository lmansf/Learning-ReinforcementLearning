_TOKEN_RE = re.compile(r"[A-Za-z_][\w-]*")
_CSS_RULES: list = []
_KIND_TOKENS: dict = {}


def _css_for(text, kind=None) -> str:
    """The subset of rs.css an output can use: a rule is kept when every class of one of its
    selectors occurs in the output's HTML or in the JS bundle that will build its DOM."""
    if not _CSS_RULES:
        for line in _asset("rs.css").splitlines():
            line = line.strip()
            if not line or line.startswith("/*"):
                continue
            if line.startswith("@"):
                _CSS_RULES.append((None, line))
                continue
            sels = line.split("{", 1)[0].split(",")
            _CSS_RULES.append(([set(re.findall(r"\.([\w-]+)", s)) for s in sels], line))
    tokens = set(_TOKEN_RE.findall(text))
    if kind:
        if kind not in _KIND_TOKENS:
            _KIND_TOKENS[kind] = set(_TOKEN_RE.findall(_asset(f"rs-{kind}.js")))
        tokens |= _KIND_TOKENS[kind]
    return "\n".join(line for sels, line in _CSS_RULES if sels is None or any(s <= tokens for s in sels))


def _page(inner="", cls="", script=None, kind=None, host_cls="rs-host") -> str:
    """One self-contained output: fonts + scoped CSS + panel (+ the JS bundle of `kind` when needed).
    Colab renders every output in its own iframe, so nothing can be shared between outputs."""
    uid = "rs-" + uuid.uuid4().hex[:10]
    body = f'<div class="rs {cls}"><div id="{uid}" class="{host_cls}">{inner}</div></div>'
    out = [FONTS, "<style>", _css_for(body, kind if script else None), "</style>", body]
    if script:
        js = _asset(f"rs-{kind}.js").replace("</script", "<\\/script")
        out += ["<script>", js, "</script><script>(function(){try{", script(uid),
                "}catch(e){console.error(e);var h=document.getElementById('" + uid + "');"
                "if(h)h.innerHTML='<p class=\"dim\">Render failed: '+e.message+'</p>';}})();</script>"]
    return "".join(out)


