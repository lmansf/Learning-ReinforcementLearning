_COURSE = {"mtime": None, "data": None}


def course() -> dict:
    """Lesson / exercise index (course.json, or built from lessons/ in a repo checkout)."""
    p = os.path.join(root(), "course.json")
    if os.path.isfile(p):
        m = os.path.getmtime(p)
        if _COURSE["mtime"] != m:
            with open(p, encoding="utf-8") as f:
                _COURSE.update(mtime=m, data=json.load(f))
        return _COURSE["data"]
    if _COURSE["data"] is None:
        _COURSE["data"] = _build_module().course_index()
    return _COURSE["data"]


def _find(lesson_id, ex_id=None):
    for l in course()["lessons"]:
        if l["id"] == lesson_id:
            if ex_id is None:
                return l, None
            for e in l["exercises"]:
                if e["id"] == ex_id:
                    return l, e
            raise KeyError(f"unknown exercise {lesson_id}/{ex_id}")
    raise KeyError(f"unknown lesson {lesson_id}")


def _check_path(lesson_id, ex_id):
    for p in (os.path.join(root(), "checks", lesson_id, ex_id, "check.py"),
              os.path.join(root(), "lessons", lesson_id, "exercises", ex_id, "check.py")):
        if os.path.isfile(p):
            return p
    return None


# ====================================================================== progress
def _pfile():
    return os.path.join(root(), "progress.json")


def _blank():
    return {"version": 1, "exercises": {}, "quizzes": {}, "hints": {}, "revealed": {}, "store": {},
            "settings": dict(DEFAULT_SETTINGS)}


def load_progress() -> dict:
    p = _blank()
    try:
        with open(_pfile(), encoding="utf-8") as f:
            data = json.load(f)
        for k, v in data.items():
            if isinstance(v, dict) and isinstance(p.get(k), dict):
                p[k].update(v)
            else:
                p[k] = v
    except FileNotFoundError:
        pass
    except (json.JSONDecodeError, OSError, AttributeError):
        try:  # keep the damaged file for the learner, start clean
            os.replace(_pfile(), _pfile().replace(".json", f".damaged-{int(time.time())}.json"))
        except OSError:
            pass
    return p


def _save(p):
    p["updated"] = time.time()
    path = _pfile()
    tmp = path + ".tmp"
    data = json.dumps(p, indent=1, sort_keys=True)
    try:
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
    except OSError:
        with open(path, "w", encoding="utf-8") as f:
            f.write(data)


def _update(fn):
    """Read-modify-write: always starts from the file on disk, so two notebooks never clobber each other."""
    p = load_progress()
    out = fn(p)
    _save(p)
    return p if out is None else out


def summary(p=None) -> dict:
    p = p or load_progress()
    xp = ex_done = ex_total = q_total = lessons_done = 0
    lessons_total = 0
    for l in course()["lessons"]:
        checked = [e for e in l["exercises"] if e["has_check"]]
        done = 0
        for e in checked:
            ex_total += 1
            if p["exercises"].get(f"{l['id']}/{e['id']}", {}).get("passed"):
                ex_done += 1
                done += 1
                xp += int(e["xp"])
        q_total += l["quizzes"]
        if checked:
            lessons_total += 1
            lessons_done += done == len(checked)
    q_done = sum(1 for k, v in p["quizzes"].items() if ":" not in k and v == "right")
    xp += QUIZ_XP * q_done
    level = xp // XP_PER_LEVEL + 1
    return {"xp": xp, "level": level, "rank": RANKS[min(level - 1, len(RANKS) - 1)],
            "into": xp % XP_PER_LEVEL, "next_rank": RANKS[min(level, len(RANKS) - 1)],
            "ex_done": ex_done, "ex_total": ex_total, "q_done": q_done, "q_total": q_total,
            "lessons_done": lessons_done, "lessons_total": lessons_total,
            "pct": round(100 * ex_done / ex_total) if ex_total else 0}


