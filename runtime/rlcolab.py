def _drive_url(filename):
    """Colab link for a notebook in the Drive folder (Drive's FUSE mount exposes file ids)."""
    try:
        fid = os.getxattr(os.path.join(root(), filename), "user.drive.id").decode()
        return f"https://colab.research.google.com/drive/{fid}"
    except Exception:
        return None


def _lesson_state(l, p):
    chk = [e for e in l["exercises"] if e["has_check"]]
    done = [bool(p["exercises"].get(f"{l['id']}/{e['id']}", {}).get("passed")) for e in chk]
    quiz = [p["quizzes"].get(f"{l['id']}#{i}") == "right" for i in range(l["quizzes"])]
    if chk and all(done):
        st = "complete"
    elif any(done) or any(quiz) or any(p["quizzes"].get(f"{l['id']}#{i}") for i in range(l["quizzes"])):
        st = "started"
    else:
        st = ""
    return chk, done, quiz, st


def lesson_footer(lesson_id):
    l, _ = _find(lesson_id)
    p = load_progress()
    chk, done, quiz, st = _lesson_state(l, p)
    strip = []
    for e in l["exercises"]:
        ok = p["exercises"].get(f"{l['id']}/{e['id']}", {}).get("passed")
        xp = ("✓" if ok else f"{e['xp']} XP") if e["has_check"] else "FREE-FORM"
        strip.append(f'<span class="rs-ex{" done" if ok else ""}"><i class="st"></i>{html.escape(e["title"])}'
                     f'<span class="xp">{xp}</span></span>')
    q_right = sum(quiz)
    lessons = course()["lessons"]
    idx = [x["id"] for x in lessons].index(l["id"])
    nxt = lessons[idx + 1] if idx + 1 < len(lessons) else None
    head = ("MISSION COMPLETE" if st == "complete" else "MISSION STATUS")
    msg = (f"All exercises cleared. " if st == "complete" else
           f"{sum(done)}/{len(chk)} exercises passed. " if chk else "Free-form mission — no checks. ")
    msg += f"Knowledge checks: {q_right}/{l['quizzes']} right."
    nxt_html = ""
    if nxt:
        url = _drive_url(nxt["notebook"])
        t = html.escape(f'{nxt["num"]} · {nxt["title"]}')
        go = f'<a class="go" href="{url}" target="_blank">OPEN ▶</a>' if url else f'<span class="go">OPEN “{html.escape(nxt["notebook"])}”</span>'
        nxt_html = (f'<div class="rs-next" style="margin:14px 0 0"><div><div class="label">NEXT MISSION ▶</div>'
                    f'<div class="t">{t}</div></div>{go}</div>')
    body = (f'<div class="rs-check-head" style="display:flex;justify-content:space-between;margin-bottom:10px">'
            f'<span class="label" style="color:{"var(--good)" if st == "complete" else "var(--accent)"}">{head}</span>'
            f'<span class="label dim">{html.escape(l["num"] + " · " + l["title"].upper())}</span></div>'
            f'<p style="color:var(--text-2)">{msg}</p><div class="rs-strip">{"".join(strip)}</div>{nxt_html}')
    _display(_HTML(_page(_top_bar(l) + '<div style="height:14px"></div>' + body, "rs-foot-panel")))


