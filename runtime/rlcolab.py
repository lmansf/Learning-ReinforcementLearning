def hud_event(ev) -> bool:
    """Render one rlhud event in the notebook. Returns True when handled."""
    _ensure_hooks()
    t = ev.get("type")
    if t in ("plot", "chart", "append"):
        cid = ev.get("id") or ev.get("title") or "Chart"
        c = _card("line", cid, ev.get("title") or cid)
        m = c["meta"]
        if t == "chart":
            m.update(smooth=ev.get("smooth", 0), xlabel=ev.get("xlabel", ""), ylabel=ev.get("ylabel", ""))
            c["title"] = ev.get("title") or c["title"]
            _touch(c)
        elif t == "plot":
            if ev.get("smooth", 0) > 1:
                m["smooth"] = ev["smooth"]
            for k in ("xlabel", "ylabel"):
                if ev.get(k):
                    m[k] = ev[k]
            c["series"][ev.get("label", "series")] = {"y": list(ev.get("y") or []), "x": ev.get("x")}
            _touch(c, live=True)
        else:
            for label, vals in (ev.get("series") or {}).items():
                s = c["series"].setdefault(label, {"y": [], "x": None})
                s["y"].extend(vals)
                s["x"] = None
            _touch(c, live=True)
        return True
    if t in ("bars", "grid", "table", "replay"):
        c = _card(t, ev.get("id") or ev.get("title"), ev.get("title", t))
        c["event"] = ev
        _touch(c, live=True)
        return True
    if t == "stat":
        c = _card("stat", "__stats__", "Stats")
        c["stats"][ev.get("name")] = ev
        _touch(c, live=True)
        return True
    if t == "text":
        _display(_HTML(_page("", "rs-vis", kind="board", script=lambda uid: f"RS.board({_js_json(uid)},{_js_json([ev])});")))
        return True
    if t == "progress":
        label = ev.get("label", "Training")
        i, n = int(ev.get("i", 0)), int(ev.get("n", 1))
        h = _PROG.get(label)
        page = _HTML(_progress_html(i, n, label))
        if h is None or h["cell"] != _S["cell"]:
            _PROG[label] = {"handle": _display(page, handle=True), "cell": _S["cell"], "last": time.time()}
        elif i >= n or time.time() - h["last"] > 0.25:
            h["handle"].update(page)
            h["last"] = time.time()
        return True
    return False
