def check(exercise_id):
    """Run an exercise's automated checks against the code you last ran in its cell.

    Like the desktop app, your code is executed again in a fresh namespace with
    __name__ == "__check__" (so the demo under `if __name__ == "__main__":` is skipped),
    then check.py runs with the helpers check / approx / require / seed_all.
    """
    lesson_id, ex_id = exercise_id.split("/", 1)
    l, e = _find(lesson_id, ex_id)
    cpath = _check_path(lesson_id, ex_id)
    if cpath is None:
        _display(_HTML(_page('<div class="rs-locked"><span class="label">FREE-FORM</span><p>This exercise has no automated checks — experiment freely.</p></div>')))
        return None
    notes = []
    src = _exercise_source(exercise_id)
    ip = _ip()
    rows = []
    t0 = time.time()
    handle = _display(_HTML(_check_panel(l, e, rows, "run", 0)), handle=True)
    last = [time.time()]

    def refresh(force=False):
        if force or time.time() - last[0] > 0.3:
            last[0] = time.time()
            handle.update(_HTML(_check_panel(l, e, rows, "run", time.time() - t0)))

    def check_(cond, label, detail=""):
        ok = bool(cond)
        rows.append({"label": str(label), "ok": ok, "detail": str(detail) if (not ok or detail) else ""})
        refresh()
        return ok

    def approx(a, b, tol=1e-6):
        try:
            import numpy as np
            return bool(np.allclose(np.asarray(a, dtype=float), np.asarray(b, dtype=float), atol=tol, rtol=0))
        except Exception:
            return abs(float(a) - float(b)) <= tol

    def seed_all(s=0):
        random.seed(s)
        try:
            import numpy as np
            np.random.seed(s)
        except Exception:
            pass

    ns = None
    if src is None:
        notes.append("⚠ Couldn't find your exercise cell in this session — checked the notebook's current variables instead. "
                     "Run the exercise cell (the one starting with “✏️ EXERCISE”), then check again.")
        ns = dict(ip.user_ns) if ip is not None else {}
        ns["__name__"] = "__check__"
    else:
        ns = {"__name__": "__check__", "__file__": os.path.join(workspace(), ex_id + ".py"), "__builtins__": builtins}
        if ip is not None:
            ns["get_ipython"] = ip.get_ipython
            from IPython.display import display
            ns["display"] = display
        linecache.cache["your_code.py"] = (len(src), None, src.splitlines(True), "your_code.py")
        try:
            exec(compile(src, "your_code.py", "exec"), ns)
        except KeyboardInterrupt:
            raise
        except BaseException as ex:  # noqa: BLE001 — report anything the learner's code raises
            check_(False, "Your code runs without errors", _user_tb(ex))
            ns = None
    if ns is not None:
        def require(name):
            if name not in ns:
                raise _Missing(f"`{name}` is not defined. Did you rename or delete it?")
            return ns[name]
        cns = dict(ns)
        cns.update(check=check_, approx=approx, require=require, seed_all=seed_all, __name__="__checker__")
        with open(cpath, encoding="utf-8") as f:
            csrc = f.read()
        try:
            exec(compile(csrc, "check.py", "exec"), cns)
        except KeyboardInterrupt:
            raise
        except _Missing as ex:
            check_(False, "Required name present", str(ex))
        except NotImplementedError as ex:
            check_(False, "Implementation complete", f"Something still raises NotImplementedError: {ex}".rstrip(": "))
        except BaseException as ex:  # noqa: BLE001
            tb = traceback.format_exception(type(ex), ex, ex.__traceback__)
            check_(False, "Checks ran to completion", "".join(tb[-6:]))
    elapsed = time.time() - t0
    total, passed = len(rows), sum(r["ok"] for r in rows)
    ok = total > 0 and passed == total
    key = exercise_id
    xp = hint = None
    s = get_settings()
    if ok:
        first = [False]

        def upd(p):
            prev = p["exercises"].get(key, {})
            first[0] = not prev.get("passed")
            p["exercises"][key] = {"passed": True, "at": prev.get("at") or time.time(), "last": time.time()}
        p = _update(upd)
        sm = summary(p)
        lesson_done = all(p["exercises"].get(f"{l['id']}/{x['id']}", {}).get("passed") for x in l["exercises"] if x["has_check"])
        text = (f"+{e['xp']} XP · {html.escape(e['title'])}" if first[0] else "Already completed — nice refactor.")
        if first[0] and lesson_done:
            text += " · MISSION COMPLETE"
        xp = {"text": text, "rank": sm["rank"], "level": sm["level"], "total": sm["xp"]}
    else:
        def upd(p):
            n = len(e.get("hints") or [])
            if s["hints"] == "on" and n:
                cur = int(p["hints"].get(key, 0))
                p["hints"][key] = min(n, cur + 1)
            p["exercises"].setdefault(key, {})["attempts"] = int(p["exercises"].get(key, {}).get("attempts", 0)) + 1
        p = _update(upd)
        n = len(e.get("hints") or [])
        if s["hints"] == "on" and n:
            k = int(p["hints"].get(key, 1))
            hint = (f"HINT {k}/{n}" + (" · MORE BELOW THIS CELL" if k < n else ""), e["hints"][k - 1])
    if elapsed > e.get("timeout", 60):
        notes.append(f"⏱ This took {elapsed:.0f}s — longer than the desktop app's {e.get('timeout', 60)}s limit. Fine here, but your training may be heavier than it needs to be.")
    handle.update(_HTML(_check_panel(l, e, rows, "pass" if ok else "fail", elapsed, xp, hint, notes)))
    log = os.environ.get("RS_RESULTS_LOG")
    if log:
        with open(log, "a", encoding="utf-8") as f:
            f.write(json.dumps({"exercise": key, "passed": passed, "total": total, "ok": ok,
                                "elapsed": round(elapsed, 2), "source": "cell" if src is not None else "globals",
                                "failed": [r for r in rows if not r["ok"]]}) + "\n")
    return {"passed": passed, "total": total, "ok": ok}


