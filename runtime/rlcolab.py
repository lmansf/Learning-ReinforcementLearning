    l, _ = _find(lesson_id)
    chk = [e for e in l["exercises"] if e["has_check"]]
    total_xp = sum(e["xp"] for e in l["exercises"])
    p = load_progress()
    complete = chk and all(p["exercises"].get(f"{l['id']}/{e['id']}", {}).get("passed") for e in chk)
